type Position = Emplacement & { adresse?: string; osm: string };
const parId = positions as Record<string, Position>;

export const lieux: Lieu[] = fiches.map((f) => {
  const p = parId[f.id];
  if (!p) return { ...f, emplacement: null };
  const { adresse, osm: _osm, ...emplacement } = p;
  return { ...f, adresse: f.adresse || adresse || '', emplacement };
});

// Les lieux qu'on peut placer sur la carte et débloquer en passant.
export const lieuxPlaces: LieuPlace[] = lieux.filter((l): l is LieuPlace => l.emplacement !== null);

export function numeroDe(lieu: Lieu): number {
  return lieux.findIndex((l) => l.id === lieu.id) + 1;
}

import type { CategorieId } from './categories';
import positions from './positions.json';

// Visible : sur la carte dès le départ. Indice : une zone floue et une devinette.
// Secret : invisible, découvert par hasard ou révélé par un défi.
// Légendaire : loin ou difficile, toujours visible. Détail dans docs/LIEUX.md.
export type Rarete = 'visible' | 'indice' | 'secret' | 'legendaire';

// Forme du timbre : portrait pour ce qui est haut, paysage pour ponts, places,
// parcs et gares, carré pour les petits lieux, grand pour quartiers et légendaires.
export type FormatTimbre = 'portrait' | 'paysage' | 'carre' | 'grand';

// Où le lieu se débloque, calculé depuis OpenStreetMap par scripts/lieux/generer.mjs.
export type Emplacement = {
  latitude: number; // le marqueur, toujours dans le lieu
  longitude: number;
  rayon_m: number; // cercle de déblocage, ou cercle qui contient tout le contour
  contour?: Contour;
};

// Contour réel : zone (parc, quartier, emprise d'un bâtiment) ou ligne (rue, canal).
// On débloque dedans ou à moins de marge_m. Traces : latitude, longitude, à la suite.
export type Contour = {
  genre: 'zone' | 'ligne';
  marge_m: number;
  traces: number[][];
};

